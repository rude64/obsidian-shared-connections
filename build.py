"""Bundle the local graph module without third-party build dependencies."""
from pathlib import Path
root = Path(__file__).resolve().parent
core = (root / 'graph.js').read_text().replace('module.exports = {buildGraph, inFolder};', '')
plugin = (root / 'src/plugin.js').read_text()
plugin = plugin.replace("const {buildGraph} = require('./graph');", core)
network = (root / 'network.js').read_text().replace("const {compileQuery} = require('./filters');", '').replace('module.exports={createSimulation,mountNetwork};', '')
plugin = plugin.replace("const {mountNetwork} = require('./network');", network)
filters = (root / 'filters.js').read_text().replace('module.exports={compileQuery,filterGraph};', '')
plugin = plugin.replace("const {filterGraph,compileQuery} = require('./filters');", filters)
(root / 'main.js').write_text('// Generated by build.py. Edit src/plugin.js or graph.js.\n' + plugin)
